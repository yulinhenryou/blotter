"""Run Alembic migrations from Python (tests, the API at start-up) without an ini file."""

from pathlib import Path

from alembic import command
from alembic.config import Config

MIGRATIONS = Path(__file__).resolve().parent / "migrations"


def alembic_config(url: str) -> Config:
    """Build an Alembic configuration for the project's migrations against ``url``."""
    config = Config()
    config.set_main_option("script_location", str(MIGRATIONS))
    # Passed as an attribute, not an ini option, so that '%' in passwords needs no escaping.
    config.attributes["url"] = url
    return config


def upgrade(url: str, revision: str = "head") -> None:
    """Migrate the database at ``url`` up to ``revision``."""
    command.upgrade(alembic_config(url), revision)


def downgrade(url: str, revision: str = "base") -> None:
    """Migrate the database at ``url`` down to ``revision``."""
    command.downgrade(alembic_config(url), revision)


def check(url: str) -> None:
    """Fail if the models and the migrated database differ (``alembic check``).

    Raises
    ------
    alembic.util.exc.AutogenerateDiffsDetected
        If autogenerate would produce a non-empty migration.
    """
    command.check(alembic_config(url))
